// Self-test of tools/ci/diff-cover.mjs. Run: node tools/ci/test-diff-cover.mjs
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { diffCover, fails, isExcluded, parseDiff, parseGoProfile, parseLcov, ranges, render } from './diff-cover.mjs';

const diff = [
  'diff --git a/pkg/a.go b/pkg/a.go', '--- a/pkg/a.go', '+++ b/pkg/a.go',
  '@@ -3,0 +4,3 @@ func x()', '+a', '+b', '+c',
  '@@ -20 +23 @@', '-old', '+new',
  'diff --git a/docs/x.md b/docs/x.md', '--- a/docs/x.md', '+++ b/docs/x.md', '@@ -1 +1 @@', '-a', '+b',
  'diff --git a/old.go b/old.go', '--- a/old.go', '+++ /dev/null', '@@ -1,2 +0,0 @@', '-x', '-y',
  'diff --git a/my file.go b/my file.go', '--- "a/my file.go"', '+++ "b/my file.go"', '@@ -0,0 +1,2 @@', '+p', '+q'
].join('\n');
const added = parseDiff(diff);
assert.deepEqual([...added.get('pkg/a.go')], [4, 5, 6, 23], 'ranges and a single-line hunk (count omitted = 1)');
assert.ok(added.has('docs/x.md'));
assert.ok(!added.has('old.go'), 'a deleted file adds nothing');
assert.deepEqual([...added.get('my file.go')], [1, 2], 'a quoted name');

const prof = parseGoProfile([
  'mode: set',
  'example.com/m/pkg/a.go:4.10,6.2 3 1',
  'example.com/m/pkg/a.go:22.5,24.3 2 0',
  'example.com/m/pkg/a.go:24.5,25.3 1 1'
].join('\n'), 'example.com/m');
assert.equal(prof.get('pkg/a.go').get(5), true);
assert.equal(prof.get('pkg/a.go').get(23), false);
assert.equal(prof.get('pkg/a.go').get(24), true, 'a line in two blocks is covered when one ran');
assert.throws(() => parseGoProfile('garbage'), /not a cover profile line/);

const lcov = parseLcov('SF:/repo/src/a.rs\nDA:1,3\nDA:2,0\nend_of_record\nSF:/repo/src/a.rs\nDA:2,1\nend_of_record\n', '/repo');
assert.equal(lcov.get('src/a.rs').get(1), true);
assert.equal(lcov.get('src/a.rs').get(2), true, 'two records of one file are merged');

let r = diffCover(added, prof, () => '');
assert.equal(r.measurable, 4, 'lines 4,5,6 and 23; line 1-2 of my file.go and the md file are not in the profile');
assert.equal(r.covered, 3);
assert.equal(r.files[0].file, 'pkg/a.go');
assert.deepEqual(r.files[0].missed, [23]);
assert.equal(r.percent, 75);
assert.equal(fails(r, { min: 80, minLines: 4 }), true);
assert.equal(fails(r, { min: 80, minLines: 5 }), false, 'a change under min-lines is not judged on a ratio');
assert.equal(fails(r, { min: 75, minLines: 1 }), false, 'exactly at the threshold passes');

r = diffCover(parseDiff('+++ b/docs/x.md\n@@ -1 +1 @@\n+b'), prof, () => '');
assert.equal(r.percent, null);
assert.equal(fails(r, { min: 80, minLines: 0 }), false, 'a docs-only change passes');
assert.match(render(r, { min: 80, minLines: 10 }), /Nothing to judge/);

// Exclusions.
assert.equal(isExcluded('pkg/a_test.go'), true);
assert.equal(isExcluded('web/src/x.test.ts'), true);
assert.equal(isExcluded('pkg/testdata/x.go'), true);
assert.equal(isExcluded('pkg/a.go'), false);
assert.equal(isExcluded('pkg/gen.go', () => '// Code generated by tool. DO NOT EDIT.\npackage x'), true);
const withTest = diffCover(parseDiff('+++ b/pkg/a_test.go\n@@ -0,0 +1 @@\n+x'), parseGoProfile('mode: set\nm/pkg/a_test.go:1.1,1.5 1 0'), () => '');
assert.equal(withTest.measurable, 0, 'a test file is not judged');

assert.equal(ranges([1, 2, 3, 7, 9, 10]), '1-3, 7, 9-10');
const md = render(diffCover(added, prof, () => ''), { min: 80, minLines: 4, reportOnly: true });
assert.match(md, /75\.0%/); assert.match(md, /`pkg\/a\.go` \| 23/); assert.match(md, /report only/);

// The command line, with a real git repo: an uncovered 10-line function fails, a covered one passes, a docs-only change passes.
const here = path.dirname(fileURLToPath(import.meta.url));
const tool = path.join(here, 'diff-cover.mjs');
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'diffcov-'));
const sh = (...a) => spawnSync(a[0], a.slice(1), { cwd: dir, encoding: 'utf8' });
const w = (n, s) => { fs.mkdirSync(path.dirname(path.join(dir, n)), { recursive: true }); fs.writeFileSync(path.join(dir, n), s); };
sh('git', 'init', '-q'); sh('git', 'config', 'user.email', 't@t'); sh('git', 'config', 'user.name', 't');
w('go.mod', 'module example.com/m\n\ngo 1.22\n');
w('pkg/a.go', 'package pkg\n');
sh('git', 'add', '-A'); sh('git', 'commit', '-qm', 'base');
const fn = Array.from({ length: 12 }, (_, i) => `\t_ = ${i}`);
w('pkg/a.go', ['package pkg', '', 'func F() {', ...fn, '}', ''].join('\n'));
w('docs/x.md', 'hello\n');
sh('git', 'add', '-A'); sh('git', 'commit', '-qm', 'change');
const run = (cover, ...extra) => spawnSync(process.execPath, [tool, '--base', 'HEAD~1', '--head', 'HEAD', '--go', path.join(dir, cover), '--out', path.join(dir, 'sum.md'), ...extra], { cwd: dir, encoding: 'utf8' });
w('none.cover', 'mode: set\nexample.com/m/pkg/a.go:3.10,16.2 13 0\n');
w('all.cover', 'mode: set\nexample.com/m/pkg/a.go:3.10,16.2 13 1\n');
let res = run('none.cover');
assert.equal(res.status, 1, res.stdout + res.stderr); assert.match(res.stdout, /::error::Diff coverage 0\.0%/);
assert.match(fs.readFileSync(path.join(dir, 'sum.md'), 'utf8'), /pkg\/a\.go/, 'the summary file is written');
res = run('none.cover', '--report-only');
assert.equal(res.status, 0); assert.match(res.stdout, /::warning::/);
res = run('all.cover');
assert.equal(res.status, 0, res.stdout + res.stderr);
res = spawnSync(process.execPath, [tool, '--base', 'HEAD~1', '--head', 'HEAD'], { cwd: dir, encoding: 'utf8' });
assert.equal(res.status, 2, 'no profile given is an input error');
res = run('missing.cover');
assert.equal(res.status, 2, 'a missing profile is an input error, not a pass');
fs.rmSync(dir, { recursive: true, force: true });
console.log('diff-cover: ok');
